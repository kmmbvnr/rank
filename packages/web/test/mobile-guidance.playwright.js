// Run against the mobile console: playwright-cli run-code --filename packages/web/test/mobile-guidance.playwright.js
async original => {
    const check = (condition, message) => { if (!condition) throw new Error(message); };
    const browser = original.context().browser();
    let context = await browser.newContext({ viewport: { width: 390, height: 844 } });
    let page = await context.newPage();
    await page.goto(original.url());
    let card = page.locator('#mobile-guidance');
    const step = name => page.waitForFunction(name => {
        const card = document.querySelector('#mobile-guidance');
        return card && !card.hidden && card.dataset.step === name;
    }, name, { timeout: 8000 }).catch(async error => { throw new Error(`Step ${name}: ${await card.textContent()} / hidden=${await card.isHidden()} / ${JSON.stringify(await saved())}: ${error.message}`); });
    const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('rank-mobile-guidance-v1')));
    const geometry = async target => {
        const box = await card.boundingBox();
        const targetBox = await target.boundingBox();
        check(box && box.x >= 0 && box.y >= 0 && box.x + box.width <= 390 && box.y + box.height <= 844, 'Hint must fit the viewport');
        check(box.y + box.height <= targetBox.y || box.y >= targetBox.y + targetBox.height, 'Hint must not cover its action');
    };
    let play = page.locator('#run-button');
    const clickCore = () => page.getByRole('tab', { name: 'core', exact: true }).click();
    await step('offer');
    await card.getByRole('button', { name: 'Insert example' }).click();
    await step('run');
    check(await page.getByRole('textbox').inputValue() === 'A * 10', 'Select the final example line');
    check(!(await page.locator('#screen').textContent()).includes('10 20 30 40 50'), 'Insertion must not execute');
    await geometry(play);
    await page.screenshot({ path: 'output/playwright/mobile-guidance-run.png' });
    await play.click();
    await step('hold');
    await page.screenshot({ path: 'output/playwright/mobile-guidance-result.png' });
    check((await page.locator('#screen').textContent()).includes('10 20 30 40 50'), 'Normal Play must evaluate both array lines');
    check(await page.locator('#guidance-spotlight').isHidden(), 'Hold hint must be nonblocking');
    await card.getByRole('button', { name: 'Got it' }).click();
    check(await card.isHidden(), 'Dismissal must not queue the next hint');
    // A separate quiet interaction resumes the guided keyboard introduction.
    await clickCore();
    await step('commands');
    check(!(await card.textContent()).includes('Dismiss the system'), 'Already visible Rank keyboard needs no OS dismissal instructions');
    const command = page.locator('#keyboard-keys button').filter({ hasText: /^false$/ });
    await command.scrollIntoViewIfNeeded();
    const box = await command.boundingBox();
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
    await page.mouse.down(); await page.waitForTimeout(650); await page.mouse.up();
    await page.locator('#key-manual').waitFor({ state: 'visible' });
    check(await card.isHidden(), 'Documentation modal must hide guidance');
    await page.getByRole('button', { name: 'Close manual' }).click();
    await step('letters');
    await geometry(page.locator('#keyboard-letters'));
    check((await saved()).documentation, 'Remember independently discovered documentation');
    await page.locator('#keyboard-letters').click();
    check((await saved()).step === 'done', 'System-keyboard action completes the tour');
    check(await card.isHidden(), 'Completion must not queue a contextual hint');
    await page.reload();
    check(await card.isHidden(), 'Reopening must not repeat the completed tour');
    await clickCore();
    await step('notebooks');
    check(await page.locator('#guidance-spotlight').isHidden(), 'Notebook hint must be nonblocking');
    await page.locator('#brand').click();
    check((await saved()).notebooks, 'Opening notebooks suppresses the notebook hint');
    await page.keyboard.press('Escape');
    await page.locator('#menu-toggle').click();
    await page.getByRole('button', { name: 'Replay walkthrough' }).click();
    await page.evaluate(() => window.rankSoftKeyboard(false));
    await step('commands');
    check((await page.locator('#screen').textContent()).includes('A * 10'), 'Replay must preserve existing code');
    check(await card.getByRole('button', { name: 'Insert example' }).count() === 0, 'Replay must not offer replacement code');
    await card.getByRole('button', { name: 'Skip', exact: true }).click();
    await page.reload();
    check(await card.isHidden(), 'Skip must persist across reopening');

    // Typing cancels the offer, preserves source, and suppresses hints while editing.
    await context.close();
    context = await browser.newContext({ viewport: { width: 390, height: 844 } });
    page = await context.newPage();
    await page.goto(original.url());
    card = page.locator('#mobile-guidance');
    play = page.locator('#run-button');
    await step('offer');
    await page.getByRole('textbox').fill('X = 42');
    await page.waitForTimeout(1100);
    check(await card.isHidden(), 'Typing must dismiss the example and suppress guidance');
    check(await page.getByRole('textbox').inputValue() === 'X = 42', 'Keep independent source');
    await page.locator('#menu-toggle').click();
    await page.getByRole('button', { name: 'Replay walkthrough' }).click();
    await page.evaluate(() => window.rankSoftKeyboard(false));
    await step('commands');
    await card.getByRole('button', { name: 'Skip', exact: true }).click();
    await play.click();
    await page.waitForFunction(() => document.querySelector('#input').getAttribute('aria-busy') === 'false');
    check(!(await saved()).executed, 'One code line must not qualify for hold guidance');
    await page.getByRole('textbox').fill('X * 2');
    await page.evaluate(() => { window.rankSoftKeyboard(true, 280); window.rankSoftKeyboard(false); });
    await play.click();
    await page.waitForFunction(() => document.querySelector('#input').getAttribute('aria-busy') === 'false');
    check((await page.locator('#screen').textContent()).includes('84'), 'Independent execution must complete');
    await clickCore();
    await step('hold');
    const playBox = await play.boundingBox();
    await page.mouse.move(playBox.x + playBox.width / 2, playBox.y + playBox.height / 2);
    await page.mouse.down(); await page.waitForTimeout(850); await page.mouse.up();
    check((await saved()).hold, 'Actual hold-to-run must suppress the hint');
    check(await card.isHidden(), 'Independent hold must dismiss its hint');

    // Native keyboard reports drive steps, rather than elapsed time.
    await page.evaluate(() => { localStorage.setItem('rank-mobile-guidance-v1', JSON.stringify({ step: 'keyboard', hold: true, notebooks: true })); });
    await page.reload();
    await page.evaluate(() => window.rankSoftKeyboard(true, 280));
    await step('keyboard');
    check((await card.textContent()).includes('Dismiss the system keyboard'), 'Explain OS keyboard dismissal above it');
    await page.waitForTimeout(1100);
    check((await saved()).step === 'keyboard', 'Time must not advance an action step');
    await page.evaluate(() => window.rankSoftKeyboard(false));
    await step('commands');
    await page.setViewportSize({ width: 844, height: 390 });
    await page.waitForTimeout(500);
    const landscape = await card.boundingBox();
    check(landscape && landscape.x >= 0 && landscape.y >= 0 && landscape.x + landscape.width <= 844
        && landscape.y + landscape.height <= 390, 'Keyboard hint must fit landscape');
    await card.getByRole('button', { name: 'Skip', exact: true }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => window.rankSoftKeyboard(true, 280));
    await page.evaluate(() => window.rankSoftKeyboard(false));
    await clickCore();
    await step('modules');
    await page.getByRole('tab', { name: 'Import a module' }).click();
    check((await saved()).modules, 'Independent module-picker use suppresses its hint');
    check(await card.isHidden(), 'Do not queue another hint after module discovery');
    await page.getByRole('textbox').fill('Missing + 1');
    await play.click();
    await page.waitForFunction(() => document.querySelector('#input').getAttribute('aria-busy') === 'false');
    check(await card.isHidden(), 'Errors must not be covered by hints');
    await page.reload();
    await clickCore();
    await page.waitForTimeout(1100);
    check(await card.isHidden(), 'Independent discoveries must survive reopening');
    await context.close();
}
